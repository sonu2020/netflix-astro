import { writeFile } from "fs/promises";
import path from "path";

const ENDPOINT = "https://query.wikidata.org/sparql";

const SPARQL_QUERY = `
SELECT ?item ?itemLabel ?poster ?pubdate ?youtubeId
       (GROUP_CONCAT(DISTINCT ?directorLabel; separator=", ") AS ?directors)
       (GROUP_CONCAT(DISTINCT ?actorLabel; separator=", ") AS ?actors)

WHERE {
  ?item wdt:P31 wd:Q11424;
        wdt:P364 wd:Q36236;
        wdt:P577 ?pubdate.
  FILTER(?pubdate >= "2024-01-01T00:00:00Z"^^xsd:dateTime)
  OPTIONAL { ?item wdt:P18 ?poster. }
  OPTIONAL { ?item wdt:P57 ?director. }
  OPTIONAL { ?item wdt:P161 ?actor. }
  OPTIONAL { ?item wdt:P1651 ?youtubeId. }
  SERVICE wikibase:label {
    bd:serviceParam wikibase:language "en".
  }
}
GROUP BY ?item ?itemLabel ?poster ?pubdate ?youtubeId
ORDER BY DESC(?pubdate)
`;

async function fetchWikidata() {
  const url = `${ENDPOINT}?query=${encodeURIComponent(SPARQL_QUERY)}&format=json`;
  const res = await fetch(url, {
    headers: {
      "Accept": "application/sparql-results+json",
      "User-Agent": "NetflixAstroProject/1.0 (personal project; contact: you@example.com)",
    },
  });
  if (!res.ok) {
    throw new Error(`Wikidata request failed: ${res.status} ${res.statusText}`);
  }
  const data = await res.json();
  return data.results.bindings;
}

function toMovieObject(row, index) {
  const title = row.itemLabel?.value ?? "Untitled";
  const pubdateRaw = row.pubdate?.value ?? null;
  const year = pubdateRaw ? new Date(pubdateRaw).getFullYear() : null;
  const releaseDate = pubdateRaw
    ? new Date(pubdateRaw).toLocaleDateString("en-US", {
        year: "numeric",
        month: "long",
        day: "numeric",
      })
    : "TBA";
  return {
    id: `wd-${index + 1}`,
    title,
    image: row.poster?.value ?? "",
    year,
    language: "Malayalam",
    releaseDate,
    director: row.directors?.value || "Unknown",
    actors: row.actors?.value || "Unknown",
    description: "",
    youtube: row.youtubeId?.value
      ? `https://www.youtube.com/embed/${row.youtubeId.value}`
      : "",
    wikidataId: row.item.value.split("/").pop(),
  };
}

async function main() {
  console.log("Fetching Malayalam movies (2024+) from Wikidata...");
  const rows = await fetchWikidata();
  console.log(`Found ${rows.length} results.`);
  const seen = new Map();
  rows.forEach((row) => {
    const id = row.item.value;
    if (!seen.has(id)) {
      seen.set(id, row);
    }
  });
  const movies = Array.from(seen.values()).map(toMovieObject);
  const outputPath = path.resolve("src/data/upcoming-wikidata.js");
  const fileContents = `// Auto-generated by scripts/fetch-wikidata.mjs
// Fetched on: ${new Date().toISOString()}
// Source: Wikidata SPARQL endpoint

export const Malayalam_Movies_2024_Plus = ${JSON.stringify(movies, null, 2)};
`;
  await writeFile(outputPath, fileContents, "utf-8");
  console.log(`Saved ${movies.length} movies to ${outputPath}`);
}

main().catch((err) => {
  console.error("Error fetching Wikidata data:", err);
  process.exit(1);
});
